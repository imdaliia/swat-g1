#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const args = process.argv.slice(2);
const write = args[0] === '--write';
const htmlRoot = path.resolve(__dirname, '../html');
const pagerCssFile = path.resolve(__dirname, '../css/pager.css');
const mainNav = /<nav\b[^>]*\saria-label=["']Main["'][^>]*>[\s\S]*?<\/nav>/gi;
const anchor = /<a\b[^>]*>/gi;
const sequenceRel = /\srel=(["'])(prev|next)\1/i;
const href = /(\shref=)(["'])[^"']*\2/i;
const labels = { prev: 'Previous', next: 'Next' };
const pagerBlock = /^[ \t]*<!-- START PAGER[\s\S]*?<!-- STOP PAGER -->[ \t]*(?:\r?\n)?/m;
const pagerLink = /<link\b[^>]*\shref=(["'])[^"']*pager\.css\1[^>]*>/i;
const stylesheet = /<link\b[^>]*\srel=(["'])stylesheet\1[^>]*>/gi;

// Relative, URL-encoded link from one file to another (folders may contain spaces).
function link(from, to) {
    return path.relative(path.dirname(from), to).split(path.sep).map(encodeURIComponent).join('/');
}

// Sets an attribute on an opening tag, replacing it if it is already there.
function setAttribute(tag, name, value) {
    const existing = new RegExp(`\\s${name}=(["'])[^"']*\\1`, 'i');
    const attribute = ` ${name}="${value}"`;
    return existing.test(tag) ? tag.replace(existing, () => attribute) : tag.replace(/\s*\/?>$/, end => attribute + end);
}

// The destination's name: its first <h1> outside the navbar, or else its <title>
// without the "HCI - " prefix / " - HCI" suffix. The text stays HTML-encoded.
function pageName(html, file) {
    const clean = text => text.replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();
    const heading = clean(html.replace(mainNav, '').match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1] ?? '');
    const title = clean(html.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i)?.[1] ?? '')
        .replace(/^HCI\s*-\s*/i, '').replace(/\s*-\s*HCI$/i, '');
    const name = heading || title;
    if (!name) throw new Error(`Expected an <h1> or a <title> in ${file}`);
    return name.replace(/"/g, '&quot;');
}

// Top bar: destination, aria-label (screen readers) and title (tooltip) of the two buttons.
function rewriteButtons(html, file, destinations, names) {
    const navs = [...html.matchAll(mainNav)];
    if (navs.length !== 1) throw new Error(`Expected one main navbar in ${file}`);

    const nav = navs[0];
    const seen = new Set();
    const updated = nav[0].replace(anchor, tag => {
        const rel = tag.match(sequenceRel)?.[2].toLowerCase();
        if (!rel) return tag;
        if (seen.has(rel) || !href.test(tag)) {
            throw new Error(`Expected one ${rel} button with an href in ${file}`);
        }
        seen.add(rel);
        const url = link(file, destinations[rel]);
        const label = `${labels[rel]}: ${names.get(destinations[rel])}`;
        const linked = tag.replace(href, (_, attribute, quote) => `${attribute}${quote}${url}${quote}`);
        return setAttribute(setAttribute(linked, 'aria-label', label), 'title', label);
    });
    if (seen.size !== 2) throw new Error(`Expected Previous and Next buttons in ${file}`);
    return html.slice(0, nav.index) + updated + html.slice(nav.index + nav[0].length);
}

// End of the page: the "Continue reading" cards, right before </main>.
function rewritePager(html, file, destinations, names, eol) {
    const withoutPager = html.replace(pagerBlock, '');
    const closings = withoutPager.match(/<\/main>/gi) ?? [];
    if (closings.length !== 1) throw new Error(`Expected one </main> in ${file}`);

    const end = withoutPager.search(/<\/main>/i);
    const lineStart = withoutPager.lastIndexOf('\n', end - 1) + 1;
    const before = withoutPager.slice(lineStart, end);
    const ownLine = before.trim() === '';
    const indent = ownLine ? before : '';
    const card = (rel, arrowFirst) => {
        const arrow = `<span aria-hidden="true">${arrowFirst ? '←' : '→'}</span>`;
        const word = rel === 'prev' ? 'previous' : 'next';
        const direction = arrowFirst ? `${arrow} ${word}` : `${word} ${arrow}`;
        return [
            `${indent}        <a class="pager-${rel}" href="${link(file, destinations[rel])}">`,
            `${indent}            <span class="pager-direction">${direction}</span>`,
            `${indent}            <span class="pager-title">${names.get(destinations[rel])}</span>`,
            `${indent}        </a>`,
        ];
    };
    const block = [
        `${indent}    <!-- START PAGER -- generated by source/scripts/update-prev-next.cjs from page-order.txt, don't edit by hand -->`,
        `${indent}    <nav class="pager" aria-label="Continue reading">`,
        ...card('prev', true),
        ...card('next', false),
        `${indent}    </nav>`,
        `${indent}    <!-- STOP PAGER -->`,
    ].join(eol) + eol;
    const at = ownLine ? lineStart : end;
    return withoutPager.slice(0, at) + (ownLine ? '' : eol) + block + withoutPager.slice(at);
}

// <head>: link to pager.css right after the last stylesheet, so it can build on it.
function rewriteStylesheet(html, file, eol) {
    const url = link(file, pagerCssFile);
    const tag = `<link rel="stylesheet" href="${url}">`;
    if (pagerLink.test(html)) return html.replace(pagerLink, () => tag);

    const headEnd = html.search(/<\/head>/i);
    if (headEnd < 0) throw new Error(`Expected a </head> in ${file}`);
    const sheets = [...html.slice(0, headEnd).matchAll(stylesheet)];
    if (!sheets.length) throw new Error(`Expected a stylesheet in the <head> of ${file}`);

    const last = sheets[sheets.length - 1];
    const after = last.index + last[0].length;
    const lineStart = html.lastIndexOf('\n', last.index - 1) + 1;
    const indent = html.slice(lineStart, last.index).match(/^[ \t]*/)[0];
    return html.slice(0, after) + eol + indent + tag + html.slice(after);
}

try {
    if (args.length && (args.length !== 1 || !write)) {
        throw new Error('Usage: node source/scripts/update-prev-next.cjs [--write]');
    }
    const order = fs.readFileSync(path.join(__dirname, 'page-order.txt'), 'utf8')
        .split(/\r?\n/).map(line => line.trim()).filter(Boolean);
    const files = order.map(page => {
        const file = path.resolve(htmlRoot, page);
        if (path.isAbsolute(page) || !file.startsWith(htmlRoot + path.sep) || path.extname(file) !== '.html') {
            throw new Error(`Expected an HTML path relative to source/html: ${page}`);
        }
        return file;
    });
    if (files.length < 2 || new Set(files).size !== files.length) {
        throw new Error('Page order must list at least two distinct pages without duplicates.');
    }
    if (!fs.existsSync(pagerCssFile)) throw new Error('Expected source/css/pager.css');

    const pages = new Map(files.map(file => [file, fs.readFileSync(file, 'utf8')]));
    const names = new Map(files.map(file => [file, pageName(pages.get(file), file)]));
    const changes = [];
    for (const [index, file] of files.entries()) {
        const html = pages.get(file);
        const eol = html.includes('\r\n') ? '\r\n' : '\n';
        const destinations = {
            prev: files[(index + files.length - 1) % files.length],
            next: files[(index + 1) % files.length],
        };
        let updated = rewriteButtons(html, file, destinations, names);
        updated = rewritePager(updated, file, destinations, names, eol);
        updated = rewriteStylesheet(updated, file, eol);
        if (updated !== html) changes.push({ file, updated });
    }
    for (const { file, updated } of changes) {
        if (write) fs.writeFileSync(file, updated);
        console.log(`${write ? 'Updated' : 'Would update'}: ${path.relative(htmlRoot, file)}`);
    }
    console.log(`${changes.length} page(s) ${write ? 'updated' : 'would change; use --write to apply'}.`);
} catch (error) {
    console.error(error.message);
    process.exitCode = 1;
}
